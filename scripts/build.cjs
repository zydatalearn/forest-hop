const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const { version } = require("../package.json");
function update(file, transform) {
    const target = path.join(root, file);
    fs.writeFileSync(target, transform(fs.readFileSync(target, "utf8")));
}
update("src/game.js", text => text.replace(/const gameVersion = "[^"]+";/, `const gameVersion = "${version}";`));
update("index.html", text => text.replace(/\?v=[\d.]+/g, "?v=" + version));
const images = fs.readdirSync(path.join(root, "assets/images"), { recursive: true })
    .filter(file => /\.webp$/.test(file)).map(file => "./assets/images/" + file.replaceAll("\\", "/"));
const files = ["./", "./index.html", "./manifest.webmanifest", "./assets/icon-192.png", "./assets/icon-512.png", `./src/style.css?v=${version}`, `./src/game.js?v=${version}`, ...images];
const template = fs.readFileSync(path.join(__dirname, "sw-template.js"), "utf8");
fs.writeFileSync(path.join(root, "sw.js"), `// Generated by npm run build.\nconst CACHE = "forest-hop-${version}";\nconst FILES = ${JSON.stringify(files, null, 4)};\n` + template);
console.log(`Built Forest Hop ${version}: ${files.length} offline resources`);
